import { ApiProperty } from '@nestjs/swagger';
import {
  INSUFFICIENT_STOCK,
  SALE_STATES,
  type PaginatedResponse,
  type SaleHistoryView,
  type SaleItemView,
  type SaleState,
  type SaleSummaryView,
  type SaleView,
  type StockConflict,
} from '@app/contracts';
import { PageMetaDto } from '../../common/dto/page-meta.dto';

// HTTP response shapes only: documented for Swagger, not validated.
// `implements` keeps them in sync with what the ERP MS returns.
export class SaleItemResponseDto implements SaleItemView {
  productId!: string;
  /** @example Yerba 1kg */
  name!: string;
  sku!: string;
  /** @example 2 */
  quantity!: number;
  /** Price at the moment of the sale (RN-07) */
  unitPrice!: number;
  /** unitPrice * quantity, rounded half-up to 2 decimals */
  subtotal!: number;
}

export class SaleHistoryResponseDto implements SaleHistoryView {
  @ApiProperty({ enum: SALE_STATES })
  state!: SaleState;
  /** null when the system made the change (RN-10) */
  userId!: string | null;
  createdAt!: Date;
}

export class SaleSummaryResponseDto implements SaleSummaryView {
  id!: string;
  /** Ticket number, generated by the database */
  saleNumber!: number;
  /** Assigned only when the sale is paid */
  receiptNumber!: number | null;
  /** Sum of the item subtotals, computed by the backend (RN-06) */
  total!: number;
  @ApiProperty({ enum: SALE_STATES })
  currentState!: SaleState;
  /** The employee who registered the sale (RN-12) */
  userId!: string;
  itemCount!: number;
  createdAt!: Date;
}

export class SaleResponseDto
  extends SaleSummaryResponseDto
  implements SaleView
{
  items!: SaleItemResponseDto[];
  history!: SaleHistoryResponseDto[];
}

export class SalePageResponseDto implements PaginatedResponse<SaleSummaryView> {
  data!: SaleSummaryResponseDto[];
  meta!: PageMetaDto;
}

export class StockConflictDto implements StockConflict {
  productId!: string;
  name!: string;
  requested!: number;
  /** What can still be sold; 0 when the product was deleted or paused */
  available!: number;
}

export class InsufficientStockResponseDto {
  /** @example 409 */
  statusCode!: number;
  /** @example Insufficient stock */
  message!: string;
  @ApiProperty({ enum: [INSUFFICIENT_STOCK] })
  code!: typeof INSUFFICIENT_STOCK;
  /** Every item that failed; nothing was written */
  items!: StockConflictDto[];
}
